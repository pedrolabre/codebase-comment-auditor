import { describe, it, expect, beforeEach } from 'vitest';
import { ref } from 'vue';
import {
  useCommentFilter,
  matchesFilters,
  isCopyrightComment,
  isLinterComment,
  isDocstringComment,
  isToolGeneratedComment
} from '../../src/composables/useCommentFilter.js';
import { useAuditState } from '../../src/composables/useAuditState.js';

describe('useCommentFilter Composable & Heuristics', () => {
  const sampleComments = [
    {
      id: 'src/main.js:1:1',
      file: 'src/main.js',
      language: 'javascript',
      type: 'line',
      category: 'development',
      startLine: 1,
      text: '// Copyright (c) 2026 Acme Corp. All rights reserved.',
      content: 'Copyright (c) 2026 Acme Corp. All rights reserved.',
      tags: [],
      hasUrl: false,
      urls: []
    },
    {
      id: 'src/utils/math.js:10:3',
      file: 'src/utils/math.js',
      language: 'javascript',
      type: 'line',
      category: 'development',
      startLine: 10,
      text: '// TODO: optimize calculation algorithm https://example.com/algo',
      content: 'TODO: optimize calculation algorithm https://example.com/algo',
      tags: ['TODO'],
      hasUrl: true,
      urls: ['https://example.com/algo']
    },
    {
      id: 'src/types.ts:5:1',
      file: 'src/types.ts',
      language: 'typescript',
      type: 'line',
      category: 'development',
      startLine: 5,
      text: '// @ts-ignore: bypass strict type checking',
      content: '@ts-ignore: bypass strict type checking',
      tags: [],
      hasUrl: false,
      urls: []
    },
    {
      id: 'src/types.ts:15:1',
      file: 'src/types.ts',
      language: 'typescript',
      type: 'docstring',
      category: 'documentation',
      startLine: 15,
      text: '/**\n * Represents a user session object.\n */',
      content: 'Represents a user session object.',
      tags: [],
      hasUrl: false,
      urls: []
    },
    {
      id: 'app/parser.py:20:1',
      file: 'app/parser.py',
      language: 'python',
      type: 'line',
      category: 'development',
      startLine: 20,
      text: '# FIXME: handle edge case when array is empty',
      content: 'FIXME: handle edge case when array is empty',
      tags: ['FIXME'],
      hasUrl: false,
      urls: []
    },
    {
      id: 'app/generated.py:1:1',
      file: 'app/generated.py',
      language: 'python',
      type: 'line',
      category: 'development',
      startLine: 1,
      text: '# @generated by protoc-gen-python. DO NOT EDIT!',
      content: '@generated by protoc-gen-python. DO NOT EDIT!',
      tags: [],
      hasUrl: false,
      urls: []
    },
    {
      id: 'styles/app.css:8:1',
      file: 'styles/app.css',
      language: 'css',
      type: 'block',
      category: 'development',
      startLine: 8,
      text: '/* HACK: temporary fix for Safari flexbox bug */',
      content: 'HACK: temporary fix for Safari flexbox bug',
      tags: ['HACK', 'BUG'],
      hasUrl: false,
      urls: []
    }
  ];

  beforeEach(() => {
    useAuditState().resetAudit();
  });

  describe('Predicados de Heurística da Allowlist', () => {
    it('detecta comentarios de copyright e licenca em varios formatos', () => {
      expect(isCopyrightComment({ text: '// Copyright 2026 Acme', content: 'Copyright 2026 Acme' })).toBe(true);
      expect(isCopyrightComment({ text: '/* MIT License */', content: 'MIT License' })).toBe(true);
      expect(isCopyrightComment({ text: '// Licensed under the Apache License, Version 2.0', content: '' })).toBe(true);
      expect(isCopyrightComment({ text: '// All rights reserved.', content: '' })).toBe(true);
      expect(isCopyrightComment({ text: '// SPDX-License-Identifier: MIT', content: '' })).toBe(true);
      expect(isCopyrightComment({ text: '// © 2026 John Doe', content: '' })).toBe(true);
      expect(isCopyrightComment({ text: '// Normal development note', content: 'Normal development note' })).toBe(false);
      expect(isCopyrightComment(null)).toBe(false);
    });

    it('detecta comentarios de linters e supressoes de regras', () => {
      expect(isLinterComment({ text: '// eslint-disable-next-line', content: 'eslint-disable-next-line' })).toBe(true);
      expect(isLinterComment({ text: '// @ts-ignore', content: '@ts-ignore' })).toBe(true);
      expect(isLinterComment({ text: '// @ts-expect-error', content: '@ts-expect-error' })).toBe(true);
      expect(isLinterComment({ text: '// prettier-ignore', content: 'prettier-ignore' })).toBe(true);
      expect(isLinterComment({ text: '# noqa: E501', content: 'noqa: E501' })).toBe(true);
      expect(isLinterComment({ text: '/* stylelint-disable */', content: 'stylelint-disable' })).toBe(true);
      expect(isLinterComment({ text: '// Normal comment about linting', content: 'Normal comment about linting' })).toBe(false);
      expect(isLinterComment(null)).toBe(false);
    });

    it('detecta docstrings formais e JSDoc', () => {
      expect(isDocstringComment({ type: 'docstring', category: 'documentation', text: '/** doc */' })).toBe(true);
      expect(isDocstringComment({ type: 'line', category: 'development', text: '/**\n * JSDoc comment\n */' })).toBe(true);
      expect(isDocstringComment({ type: 'line', category: 'development', text: '"""Python docstring"""' })).toBe(true);
      expect(isDocstringComment({ type: 'line', category: 'development', text: "'''Single-quote docstring'''" })).toBe(true);
      expect(isDocstringComment({ type: 'line', category: 'development', text: '// Regular comment' })).toBe(false);
      expect(isDocstringComment(null)).toBe(false);
    });

    it('detecta comentarios de arquivos gerados automaticamente por ferramentas', () => {
      expect(isToolGeneratedComment({ text: '// @generated', content: '@generated' })).toBe(true);
      expect(isToolGeneratedComment({ text: '// DO NOT EDIT', content: 'DO NOT EDIT' })).toBe(true);
      expect(isToolGeneratedComment({ text: '// Auto-generated by OpenAPI Generator', content: '' })).toBe(true);
      expect(isToolGeneratedComment({ text: '// Code generated by tool. DO NOT EDIT.', content: '' })).toBe(true);
      expect(isToolGeneratedComment({ text: '// Just a general remark', content: 'Just a general remark' })).toBe(false);
      expect(isToolGeneratedComment(null)).toBe(false);
    });
  });

  describe('Funcao matchesFilters isolada', () => {
    it('retorna true quando nenhum filtro esta ativo', () => {
      const comment = sampleComments[0];
      expect(matchesFilters(comment, {})).toBe(true);
    });

    it('filtra por Allowlist rules', () => {
      const copyrightComment = sampleComments[0];
      const linterComment = sampleComments[2];
      const docstringComment = sampleComments[3];
      const generatedComment = sampleComments[5];

      expect(matchesFilters(copyrightComment, { hideCopyright: true })).toBe(false);
      expect(matchesFilters(copyrightComment, { hideCopyright: false })).toBe(true);

      expect(matchesFilters(linterComment, { hideLinters: true })).toBe(false);
      expect(matchesFilters(linterComment, { hideLinters: false })).toBe(true);

      expect(matchesFilters(docstringComment, { hideDocstrings: true })).toBe(false);
      expect(matchesFilters(docstringComment, { hideDocstrings: false })).toBe(true);

      expect(matchesFilters(generatedComment, { hideToolGenerated: true })).toBe(false);
      expect(matchesFilters(generatedComment, { hideToolGenerated: false })).toBe(true);
    });

    it('filtra por linguagens selecionadas', () => {
      const jsComment = sampleComments[1];
      const pyComment = sampleComments[4];

      expect(matchesFilters(jsComment, { selectedLanguages: ['javascript'] })).toBe(true);
      expect(matchesFilters(jsComment, { selectedLanguages: ['python'] })).toBe(false);
      expect(matchesFilters(pyComment, { selectedLanguages: ['javascript', 'python'] })).toBe(true);
    });

    it('filtra por tags e URLs', () => {
      const todoComment = sampleComments[1];
      const fixmeComment = sampleComments[4];
      const hackComment = sampleComments[6];

      expect(matchesFilters(todoComment, { selectedTags: ['TODO'] })).toBe(true);
      expect(matchesFilters(todoComment, { selectedTags: ['FIXME'] })).toBe(false);
      expect(matchesFilters(fixmeComment, { selectedTags: ['FIXME'] })).toBe(true);
      expect(matchesFilters(hackComment, { selectedTags: ['BUG'] })).toBe(true);
      expect(matchesFilters(todoComment, { selectedTags: ['URL'] })).toBe(true);
      expect(matchesFilters(fixmeComment, { selectedTags: ['URL'] })).toBe(false);
      expect(matchesFilters(todoComment, { onlyWithUrls: true })).toBe(true);
      expect(matchesFilters(fixmeComment, { onlyWithUrls: true })).toBe(false);
    });

    it('filtra por busca textual combinada', () => {
      const comment = sampleComments[1];

      expect(matchesFilters(comment, { searchQuery: 'calculation' })).toBe(true);
      expect(matchesFilters(comment, { searchQuery: 'math.js' })).toBe(true);
      expect(matchesFilters(comment, { searchQuery: 'TODO' })).toBe(true);
      expect(matchesFilters(comment, { searchQuery: '10' })).toBe(true);
      expect(matchesFilters(comment, { searchQuery: 'nonexistent_phrase' })).toBe(false);
    });
  });

  describe('useCommentFilter Composable', () => {
    it('inicializa com os estados padrao vazios', () => {
      const filter = useCommentFilter(sampleComments);

      expect(filter.searchQuery.value).toBe('');
      expect(filter.selectedLanguages.value).toEqual([]);
      expect(filter.selectedTags.value).toEqual([]);
      expect(filter.onlyWithUrls.value).toBe(false);
      expect(filter.hideCopyright.value).toBe(false);
      expect(filter.hideLinters.value).toBe(false);
      expect(filter.hideDocstrings.value).toBe(false);
      expect(filter.hideToolGenerated.value).toBe(false);
      expect(filter.hasActiveFilters.value).toBe(false);
      expect(filter.totalCount.value).toBe(7);
      expect(filter.filteredCount.value).toBe(7);
      expect(filter.filteredComments.value.length).toBe(7);
    });

    it('calcula contadores dinamicos de linguagens e tags', () => {
      const filter = useCommentFilter(sampleComments);

      expect(filter.availableLanguages.value).toEqual(['css', 'javascript', 'python', 'typescript']);
      expect(filter.languageCounts.value).toEqual({
        javascript: 2,
        typescript: 2,
        python: 2,
        css: 1
      });

      expect(filter.availableTags.value).toContain('TODO');
      expect(filter.availableTags.value).toContain('FIXME');
      expect(filter.availableTags.value).toContain('HACK');
      expect(filter.availableTags.value).toContain('BUG');
      expect(filter.availableTags.value).toContain('URL');
      expect(filter.tagCounts.value['TODO']).toBe(1);
      expect(filter.tagCounts.value['URL']).toBe(1);
    });

    it('alterna linguagens ativas via toggleLanguage', () => {
      const filter = useCommentFilter(sampleComments);

      filter.toggleLanguage('javascript');
      expect(filter.selectedLanguages.value).toEqual(['javascript']);
      expect(filter.filteredCount.value).toBe(2);

      filter.toggleLanguage('python');
      expect(filter.selectedLanguages.value).toEqual(['javascript', 'python']);
      expect(filter.filteredCount.value).toBe(4);

      filter.toggleLanguage('javascript');
      expect(filter.selectedLanguages.value).toEqual(['python']);
      expect(filter.filteredCount.value).toBe(2);
    });

    it('alterna tags ativas via toggleTag', () => {
      const filter = useCommentFilter(sampleComments);

      filter.toggleTag('TODO');
      expect(filter.selectedTags.value).toEqual(['TODO']);
      expect(filter.filteredCount.value).toBe(1);

      filter.toggleTag('FIXME');
      expect(filter.selectedTags.value).toEqual(['TODO', 'FIXME']);
      expect(filter.filteredCount.value).toBe(2);

      filter.toggleTag('TODO');
      expect(filter.selectedTags.value).toEqual(['FIXME']);
      expect(filter.filteredCount.value).toBe(1);
    });

    it('alterna regras da Allowlist via toggleAllowlistRule', () => {
      const filter = useCommentFilter(sampleComments);

      filter.toggleAllowlistRule('hideCopyright');
      expect(filter.hideCopyright.value).toBe(true);
      expect(filter.filteredCount.value).toBe(6);

      filter.toggleAllowlistRule('hideLinters');
      expect(filter.hideLinters.value).toBe(true);
      expect(filter.filteredCount.value).toBe(5);

      filter.toggleAllowlistRule('hideDocstrings');
      expect(filter.hideDocstrings.value).toBe(true);
      expect(filter.filteredCount.value).toBe(4);

      filter.toggleAllowlistRule('hideToolGenerated');
      expect(filter.hideToolGenerated.value).toBe(true);
      expect(filter.filteredCount.value).toBe(3);

      filter.toggleAllowlistRule('hideCopyright');
      expect(filter.hideCopyright.value).toBe(false);
      expect(filter.filteredCount.value).toBe(4);
    });

    it('aplica busca textual por substring mantendo performance instantanea', () => {
      const filter = useCommentFilter(sampleComments);

      filter.searchQuery.value = 'Safari';
      expect(filter.filteredCount.value).toBe(1);
      expect(filter.filteredComments.value[0].file).toBe('styles/app.css');

      filter.searchQuery.value = 'main.js';
      expect(filter.filteredCount.value).toBe(1);
      expect(filter.filteredComments.value[0].file).toBe('src/main.js');

      filter.searchQuery.value = 'nonexistent';
      expect(filter.filteredCount.value).toBe(0);
    });

    it('aplica combinacao complexa de filtros e permite restaurar via resetFilters', () => {
      const filter = useCommentFilter(sampleComments);

      filter.searchQuery.value = 'algo';
      filter.toggleLanguage('javascript');
      filter.toggleTag('TODO');
      filter.toggleAllowlistRule('hideLinters');

      expect(filter.hasActiveFilters.value).toBe(true);
      expect(filter.filteredCount.value).toBe(1);

      filter.resetFilters();

      expect(filter.searchQuery.value).toBe('');
      expect(filter.selectedLanguages.value).toEqual([]);
      expect(filter.selectedTags.value).toEqual([]);
      expect(filter.hideCopyright.value).toBe(false);
      expect(filter.hideLinters.value).toBe(false);
      expect(filter.hideDocstrings.value).toBe(false);
      expect(filter.hideToolGenerated.value).toBe(false);
      expect(filter.hasActiveFilters.value).toBe(false);
      expect(filter.filteredCount.value).toBe(7);
    });

    it('reage a mudancas dinamicas no array reativo de comentarios', () => {
      const reactiveComments = ref([...sampleComments]);
      const filter = useCommentFilter(reactiveComments);

      expect(filter.totalCount.value).toBe(7);

      reactiveComments.value = reactiveComments.value.slice(0, 3);
      expect(filter.totalCount.value).toBe(3);
      expect(filter.filteredCount.value).toBe(3);
    });
  });
});
